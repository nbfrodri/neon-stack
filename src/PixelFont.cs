using System;
using System.Collections.Generic;
using System.Drawing;

namespace NeonStack
{
    // A tiny original 5x7 bitmap alphabet: crisp at every integer scale, no font assets.
    internal static class PixelFont
    {
        private static readonly Dictionary<char, string[]> Glyphs = new Dictionary<char, string[]>();
        static PixelFont()
        {
            string[] glyphs = {
                "A:01110/10001/10001/11111/10001/10001/10001", "B:11110/10001/10001/11110/10001/10001/11110",
                "C:01111/10000/10000/10000/10000/10000/01111", "D:11110/10001/10001/10001/10001/10001/11110",
                "E:11111/10000/10000/11110/10000/10000/11111", "F:11111/10000/10000/11110/10000/10000/10000",
                "G:01111/10000/10000/10111/10001/10001/01111", "H:10001/10001/10001/11111/10001/10001/10001",
                "I:11111/00100/00100/00100/00100/00100/11111", "J:00111/00010/00010/00010/10010/10010/01100",
                "K:10001/10010/10100/11000/10100/10010/10001", "L:10000/10000/10000/10000/10000/10000/11111",
                "M:10001/11011/10101/10101/10001/10001/10001", "N:10001/11001/11001/10101/10011/10011/10001",
                "O:01110/10001/10001/10001/10001/10001/01110", "P:11110/10001/10001/11110/10000/10000/10000",
                "Q:01110/10001/10001/10001/10101/10010/01101", "R:11110/10001/10001/11110/10100/10010/10001",
                "S:01111/10000/10000/01110/00001/00001/11110", "T:11111/00100/00100/00100/00100/00100/00100",
                "U:10001/10001/10001/10001/10001/10001/01110", "V:10001/10001/10001/10001/10001/01010/00100",
                "W:10001/10001/10001/10101/10101/10101/01010", "X:10001/10001/01010/00100/01010/10001/10001",
                "Y:10001/10001/01010/00100/00100/00100/00100", "Z:11111/00001/00010/00100/01000/10000/11111",
                "0:01110/10001/10011/10101/11001/10001/01110", "1:00100/01100/00100/00100/00100/00100/01110",
                "2:01110/10001/00001/00010/00100/01000/11111", "3:11110/00001/00001/01110/00001/00001/11110",
                "4:00010/00110/01010/10010/11111/00010/00010", "5:11111/10000/10000/11110/00001/00001/11110",
                "6:01110/10000/10000/11110/10001/10001/01110", "7:11111/00001/00010/00100/01000/01000/01000",
                "8:01110/10001/10001/01110/10001/10001/01110", "9:01110/10001/10001/01111/00001/00001/01110",
                "-:00000/00000/00000/11111/00000/00000/00000", ".:00000/00000/00000/00000/00000/00110/00110",
                "::00000/00100/00100/00000/00100/00100/00000", "/:00001/00001/00010/00100/01000/10000/10000",
                "+:00000/00100/00100/11111/00100/00100/00000", ">:10000/01000/00100/00010/00100/01000/10000",
                "_:00000/00000/00000/00000/00000/00000/11111"
            };
            foreach (string glyph in glyphs) Glyphs[glyph[0]] = glyph.Substring(2).Split('/');
        }

        public static int Width(string text, int scale) { return Math.Max(0, text.Length * 6 - 1) * scale; }
        public static void Draw(Graphics g, string text, float x, float y, int scale, Color color)
        {
            System.Drawing.Drawing2D.SmoothingMode smoothing = g.SmoothingMode;
            using (System.Drawing.Drawing2D.Matrix transform = g.Transform)
                if (transform.Elements[0] < 1) g.SmoothingMode = System.Drawing.Drawing2D.SmoothingMode.AntiAlias;
            using (SolidBrush brush = new SolidBrush(color))
            {
                foreach (char c in text.ToUpperInvariant())
                {
                    string[] rows;
                    if (Glyphs.TryGetValue(c, out rows))
                        for (int row = 0; row < 7; row++) for (int col = 0; col < 5; col++)
                            if (rows[row][col] == '1') g.FillRectangle(brush, x + col * scale, y + row * scale, scale, scale);
                    x += 6 * scale;
                }
            }
            g.SmoothingMode = smoothing;
        }
    }
}
